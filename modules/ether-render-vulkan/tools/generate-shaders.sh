#!/usr/bin/env bash
# Regenerates the SPIR-V shader assets embedded in the Vulkan backend.
#
# Requirements:
#   - glslangValidator on PATH, or GLSLANG_VALIDATOR pointing at the binary.
#
# The generated Kotlin source file is checked in so the build never depends on a
# shader compiler being installed. Pass --skip-compile to regenerate the Kotlin
# source from the committed .spv files without running the shader compiler.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
module_dir="$(cd "$here/.." && pwd)"
assets_dir="$module_dir/assets/shaders"
output_file="$module_dir/src/dev/instrum/ether/render/vulkan/internal/shaders/BuiltinShaders.kt"

skip_compile=false
if [[ "${1:-}" == "--skip-compile" ]]; then
    skip_compile=true
fi

if [[ "$skip_compile" == false ]]; then
    validator="${GLSLANG_VALIDATOR:-glslangValidator}"
    if ! command -v "$validator" >/dev/null 2>&1; then
        echo "glslangValidator not found; set GLSLANG_VALIDATOR to its path" >&2
        echo "use --skip-compile to regenerate from the committed .spv files" >&2
        exit 1
    fi

    mkdir -p "$assets_dir"

    "$validator" -V --target-env vulkan1.3 -o "$assets_dir/triangle.vert.spv" "$assets_dir/triangle.vert"
    "$validator" -V --target-env vulkan1.3 -o "$assets_dir/triangle.frag.spv" "$assets_dir/triangle.frag"
fi

python3 - "$assets_dir" "$output_file" <<'PY'
import base64
import pathlib
import sys

assets_dir = pathlib.Path(sys.argv[1])
output_file = pathlib.Path(sys.argv[2])

CHUNK = 72


def encode(path: pathlib.Path) -> str:
    """Encode a binary file as Base64 split into Kotlin string literal chunks."""
    raw = path.read_bytes()
    encoded = base64.b64encode(raw).decode("ascii")
    chunks = [encoded[index:index + CHUNK] for index in range(0, len(encoded), CHUNK)]
    return chunks


def literal(chunks: list[str], indent: str) -> str:
    """Render Base64 chunks as a sequence of Kotlin string literals."""
    lines = []
    for index, chunk in enumerate(chunks):
        suffix = " +" if index < len(chunks) - 1 else ""
        lines.append(f'{indent}"{chunk}"{suffix}')
    return "\n".join(lines) + "\n"


header = '''// Generated by modules/ether-render-vulkan/tools/generate-shaders.sh. Do not edit by hand.
//
// Source GLSL lives in modules/ether-render-vulkan/assets/shaders/. The SPIR-V binaries are
// committed next to it so the build does not require a shader compiler.

package dev.instrum.ether.render.vulkan.internal.shaders

import kotlin.io.encoding.Base64

/**
 * SPIR-V shader binaries shipped with the Vulkan backend.
 */
internal object BuiltinShaders {

    /** Vertex stage of the built-in test triangle. */
    val TriangleVertex: ByteArray = decode(TRIANGLE_VERTEX_SPIRV)

    /** Fragment stage of the built-in test triangle. */
    val TriangleFragment: ByteArray = decode(TRIANGLE_FRAGMENT_SPIRV)

    private fun decode(encoded: String): ByteArray = Base64.Default.decode(encoded)

'''

body = []
for name, const in (
    ("triangle.vert.spv", "TRIANGLE_VERTEX_SPIRV"),
    ("triangle.frag.spv", "TRIANGLE_FRAGMENT_SPIRV"),
):
    chunks = encode(assets_dir / name)
    if not chunks:
        raise SystemExit(f"{name} is empty")
    body.append(
        f"    private const val {const}: String =\n" + literal(chunks, "        ")
    )

output_file.parent.mkdir(parents=True, exist_ok=True)
output_file.write_text(header + "\n".join(body) + "}\n", encoding="utf-8")
print(f"wrote {output_file}")
PY
